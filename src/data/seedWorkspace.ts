export function applySeedFinance<T extends { slug: string; paid: number; paymentStatus: ActiveProject["paymentStatus"] }>(
  project: T,
): T {
  const finance = seedProjectFinance[project.slug];
  if (!finance) return project;
  return {
    ...project,
    paid: finance.paid,
    paymentStatus: finance.paymentStatus,
  };
}
